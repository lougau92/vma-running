"""Embed the contract in Dart. Run after changing the JSON Schema."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KEYWORDS = {
    '$schema', '$defs', '$ref', 'title', 'description', 'default',
    'type', 'properties', 'additionalProperties', 'required', 'const', 'enum',
    'minimum', 'maximum', 'exclusiveMinimum', 'minLength', 'minItems', 'maxItems',
    'items', 'allOf', 'oneOf', 'if', 'then', 'else', 'not', 'format',
}


def check(schema):
    unknown = schema.keys() - KEYWORDS
    if unknown:
        raise ValueError(f'Add Dart validator support before using {sorted(unknown)}')
    if schema.get('format') not in (None, 'date', 'date-time'):
        raise ValueError('Add Dart support for this format')
    for group in ('properties', '$defs'):
        for child in schema.get(group, {}).values():
            check(child)
    for group in ('oneOf', 'allOf'):
        for child in schema.get(group, []):
            check(child)
    for key in ('items', 'if', 'then', 'else', 'not'):
        if key in schema:
            check(schema[key])


schema = json.loads((ROOT / 'docs/workouts/workout.schema.json').read_text())
check(schema)
text = json.dumps(schema, ensure_ascii=False, indent=2).replace('$', r'\$')
(ROOT / 'lib/workouts/workout_schema.g.dart').write_text(
    '// Generated by tool/scripts/generate_workout_schema.py; do not edit.\n'
    'const Map<String, dynamic> workoutSchema = ' + text + ';\n')
